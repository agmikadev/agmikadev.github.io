import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { MISSION_ARCHIVE } from "../src/components/Planetary/data/MissionData";
import { beltDataModel } from "../src/components/Planetary/data/BeltData";
import { canonicalTechList } from "../src/components/Planetary/data/technologies";

const __dirname = dirname(fileURLToPath(import.meta.url));
const outputPath = resolve(__dirname, "../worker/seed.sql");

function sqlString(value: string | null | undefined): string {
  if (value == null) return "NULL";
  return `'${value.replace(/'/g, "''")}'`;
}

function sqlJson(value: unknown): string {
  return sqlString(JSON.stringify(value));
}

function missionRow(
  mission: (typeof MISSION_ARCHIVE)[number] & {
    imageUrl?: string;
    featured?: boolean;
  },
  isBelt: 0 | 1,
  sortOrder: number,
): string {
  return `INSERT OR REPLACE INTO missions (
  id, title, year, role, summary, planet_ids, highlights, challenges, impact,
  ai_workflow, technologies, links, perspectives, image_url, featured, is_belt, sort_order
) VALUES (
  ${sqlString(mission.id)},
  ${sqlString(mission.title)},
  ${sqlString(mission.year)},
  ${sqlString(mission.role)},
  ${sqlString(mission.summary)},
  ${sqlJson(mission.planetIds)},
  ${sqlJson(mission.highlights)},
  ${sqlString(mission.challenges)},
  ${sqlString(mission.impact)},
  ${sqlString(mission.aiWorkflow)},
  ${sqlJson(canonicalTechList(mission.technologies))},
  ${sqlJson(mission.external_links ?? [])},
  ${sqlJson(mission.perspectives ?? {})},
  ${sqlString(mission.imageUrl)},
  ${mission.featured ? 1 : 0},
  ${isBelt},
  ${sortOrder}
);`;
}

const planetRows = MISSION_ARCHIVE.map((mission, index) =>
  missionRow(mission, 0, index),
);

const beltRows = beltDataModel.missionReports.map((report, index) =>
  missionRow(
    {
      ...report,
      planetIds: [],
      featured: report.featured ?? true,
    },
    1,
    index,
  ),
);

const header = `-- Generated by scripts/generate-d1-seed.ts
-- Do not edit by hand. Run: npm run d1:seed:generate
-- Source of truth: src/components/Planetary/data/{MissionData,BeltData}.ts
`;

const sql = `${header}
DELETE FROM missions;

${planetRows.join("\n\n")}

${beltRows.join("\n\n")}
`;

mkdirSync(dirname(outputPath), { recursive: true });
writeFileSync(outputPath, sql, "utf8");

console.log(
  `Generated ${planetRows.length} planet missions + ${beltRows.length} belt reports -> ${outputPath}`,
);
